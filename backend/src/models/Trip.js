import { Schema, model } from 'mongoose';

const attendanceSummarySchema = new Schema(
  {
    total: { type: Number, default: 0, min: 0 },
    pickedUp: { type: Number, default: 0, min: 0 },
    dropped: { type: Number, default: 0, min: 0 },
    absent: { type: Number, default: 0, min: 0 },
    pendingPickup: { type: Number, default: 0, min: 0 },
    pendingDrop: { type: Number, default: 0, min: 0 },
  },
  { _id: false }
);

const tripSchema = new Schema(
  {
    assignment: { type: Schema.Types.ObjectId, ref: 'TransportAssignment', required: true },
    vehicle: { type: Schema.Types.ObjectId, ref: 'Vehicle', required: true, index: true },
    driver: { type: Schema.Types.ObjectId, ref: 'Driver', required: true, index: true },
    route: { type: Schema.Types.ObjectId, ref: 'Route', required: true },
    date: { type: String, required: true, match: /^\d{4}-\d{2}-\d{2}$/, index: true },
    direction: { type: String, enum: ['morning', 'afternoon'], index: true },
    status: {
      type: String,
      enum: ['scheduled', 'assigned', 'ready', 'in_progress', 'delayed', 'paused', 'arrived_at_school', 'completed', 'cancelled'],
      default: 'scheduled',
      index: true,
    },
    scheduledStartAt: Date,
    scheduledEndAt: Date,
    startedAt: Date,
    arrivedAtSchoolAt: Date,
    departedSchoolAt: Date,
    completedAt: Date,
    substituteDriver: { type: Schema.Types.ObjectId, ref: 'Driver' },
    substituteVehicle: { type: Schema.Types.ObjectId, ref: 'Vehicle' },
    delayMinutes: { type: Number, min: 0 },
    delayReason: { type: String, trim: true, maxlength: 500 },
    cancelledAt: Date,
    cancelledBy: { type: Schema.Types.ObjectId, ref: 'User' },
    cancellationReason: { type: String, trim: true, maxlength: 500 },
    autoGenerated: { type: Boolean, default: false },
    gpsTrackingActive: { type: Boolean, default: false },
    lastGpsUpdateAt: Date,
    // Snapshot values captured when the trip is generated so later assignment
    // edits never rewrite completed trip history.
    expectedStudentCount: { type: Number, min: 0 },
    routeDistanceKm: { type: Number, min: 0 },
    routeDurationMinutes: { type: Number, min: 0 },
    attendanceSummary: { type: attendanceSummarySchema, default: () => ({}) },
    // Explicit, audited administrator override used when a trip must be closed
    // with unresolved student events (for example a no-show not yet recorded).
    completionOverride: {
      by: { type: Schema.Types.ObjectId, ref: 'User' },
      reason: { type: String, trim: true, maxlength: 500 },
      at: Date,
    },
  },
  { timestamps: true }
);

tripSchema.index({ assignment: 1, date: 1, direction: 1 }, { unique: true, partialFilterExpression: { direction: { $exists: true } } });
tripSchema.index({ date: 1, status: 1 });
tripSchema.index({ driver: 1, date: 1, status: 1 });
tripSchema.index({ vehicle: 1, date: 1, status: 1 });
tripSchema.index({ status: 1, lastGpsUpdateAt: 1 });

export const Trip = model('Trip', tripSchema);
