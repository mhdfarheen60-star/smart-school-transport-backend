import mongoose from 'mongoose';
import { env } from '../src/config/env.js';

async function migrate() {
  await mongoose.connect(env.mongoUri, { serverSelectionTimeoutMS: 10000 });
  const db = mongoose.connection.db;
  const trips = db.collection('trips');

  console.log('Existing indexes on trips:');
  const indexes = await trips.indexes();
  for (const idx of indexes) {
    console.log(' -', JSON.stringify(idx.key), idx.name, idx.unique ? 'UNIQUE' : '', idx.partialFilterExpression ? 'PARTIAL' : '');
  }

  // Drop the old unique index on { assignment: 1, date: 1 } if it exists
  const oldIndex = indexes.find((i) => i.key && i.key.assignment === 1 && i.key.date === 1 && !i.key.direction);
  if (oldIndex) {
    console.log(`Dropping old index: ${oldIndex.name}`);
    await trips.dropIndex(oldIndex.name);
    console.log('Old index dropped.');
  } else {
    console.log('Old unique index not found (may already be migrated).');
  }

  // Backfill direction for existing trips that have none
  const result = await trips.updateMany(
    { direction: { $exists: false } },
    { $set: { direction: 'morning', autoGenerated: false } }
  );
  console.log(`Backfilled direction for ${result.modifiedCount} existing trip(s).`);

  // Create the new unique composite index with direction
  const existingNames = (await trips.indexes()).map((i) => i.name);
  if (!existingNames.includes('assignment_1_date_1_direction_1')) {
    await trips.createIndex(
      { assignment: 1, date: 1, direction: 1 },
      {
        unique: true,
        name: 'assignment_1_date_1_direction_1',
        partialFilterExpression: { direction: { $exists: true } },
      }
    );
    console.log('Created new unique index: assignment_1_date_1_direction_1');
  } else {
    console.log('New composite index already exists.');
  }

  console.log('Final indexes on trips:');
  const finalIndexes = await trips.indexes();
  for (const idx of finalIndexes) {
    console.log(' -', JSON.stringify(idx.key), idx.name, idx.unique ? 'UNIQUE' : '', idx.partialFilterExpression ? 'PARTIAL' : '');
  }

  await mongoose.disconnect();
  console.log('Migration complete.');
}

migrate().catch((err) => {
  console.error('Migration failed:', err);
  process.exit(1);
});
